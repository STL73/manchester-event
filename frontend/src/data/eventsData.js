// Mock dates counted from today, so Tonight, This weekend and Next 7 days on
// Home and Explore Events always have something in them. Real dates will
// come from the database; events further out keep fixed dates.
function localDatetime(date, time) {
  const pad = (number) => String(number).padStart(2, "0");
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}T${time}:00`;
}

function daysFromToday(days, time) {
  const today = new Date();
  return localDatetime(new Date(today.getFullYear(), today.getMonth(), today.getDate() + days), time);
}

// Friday, Saturday or Sunday of this weekend: the one in progress on a
// Saturday or Sunday, otherwise the next one (same rule as lib/eventDates.js)
function thisWeekend(day, time) {
  const weekday = new Date().getDay();
  const toFriday = weekday === 6 || weekday === 0 ? -((weekday + 2) % 7) : (5 - weekday + 7) % 7;
  return daysFromToday(toFriday + { friday: 0, saturday: 1, sunday: 2 }[day], time);
}

